    if (!admin) {
        console.error('No admin user found');
        process.exit(1);
    }

    const dbNames = new Set(
        (await Product.find({}).select('name').lean()).map((p) => String(p.name).toLowerCase().trim())
    );

    const toAdd = MISSING.filter((p) => !dbNames.has(p.name.toLowerCase().trim()));

    console.log(`Missing definitions: ${MISSING.length}`);
    console.log(`Not yet in DB:        ${toAdd.length}`);

    toAdd.forEach((p, i) => console.log(`${i + 1}. ${p.name}  →  Tk ${p.price} / ${p.cuttedPrice}-${p.maxCutted}`));

    if (!APPLY) {
        console.log('\n(dry run — re-run with --apply to insert)');
        await mongoose.disconnect();
        return;
    }

    const docs = toAdd.map((p) => ({
        name: p.name,
        description: p.description,
        highlights: p.highlights,
        specifications: p.specifications,
        price: p.price,
        cuttedPrice: p.maxCutted, // the higher end of the suggested retail range
        images: img(p.image),
        brand: { name: p.brand, logo: { public_id: '', url: '' } },
        category: p.category,
        stock: p.stock,
        warranty: 0,
        colors: p.colors,
        inTheBox: p.inTheBox,
        ratings: 0,
        numOfReviews: 0,
        user: admin._id,
        source: 'local',
        featured: false,
        createdAt: new Date(),
    }));

    const inserted = await Product.insertMany(docs);
    console.log(`\nInserted ${inserted.length} products ✓`);
